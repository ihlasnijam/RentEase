package com.example.rentease

import android.app.Activity
import android.content.Intent
import android.net.Uri
import android.os.Bundle
import android.provider.OpenableColumns
import android.view.View
import android.widget.LinearLayout
import android.widget.ProgressBar
import android.widget.TextView
import android.widget.Toast
import androidx.appcompat.app.AlertDialog
import androidx.appcompat.app.AppCompatActivity

class DocumentsActivity : AppCompatActivity() {

    private val PICK_FILE_REQUEST = 101
    private var selectedDocType   = "General"

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        setContentView(R.layout.activity_documents)
        setupClickListeners()
        loadMyDocuments()
    }

    private fun setupClickListeners() {
        findViewById<LinearLayout>(R.id.btnBack).setOnClickListener { finish() }

        // Upload button
        findViewById<TextView>(R.id.btnUploadDoc).setOnClickListener {
            showUploadTypeDialog()
        }

        // Static document rows (tap to view content)
        try { findViewById<LinearLayout>(R.id.rowLeaseDoc).setOnClickListener {
            showDocumentContent("Tenancy Agreement",
                "Property: ${SessionManager.getName(this)}'s Rental\n" +
                "Period: Jan 1, 2025 – Dec 31, 2025\nRent: AED 4,500/month\n" +
                "Governed by RERA Dubai regulations.")
        }} catch (e: Exception) {}

        try { findViewById<LinearLayout>(R.id.rowReceiptMarch).setOnClickListener {
            showDocumentContent("Receipt — March 2025",
                "Tenant: ${SessionManager.getName(this)}\nAmount: AED 4,500\nPaid: Mar 7, 2025\nStatus: Paid")
        }} catch (e: Exception) {}

        try { findViewById<LinearLayout>(R.id.rowReceiptFeb).setOnClickListener {
            showDocumentContent("Receipt — February 2025",
                "Tenant: ${SessionManager.getName(this)}\nAmount: AED 4,500\nPaid: Feb 5, 2025\nStatus: Paid")
        }} catch (e: Exception) {}

        try { findViewById<LinearLayout>(R.id.rowMonthlyReport).setOnClickListener {
            showDocumentContent("Monthly Summary — April 2025",
                "Open requests: 2\nPayments: April pending\nMessages: 3 unread\n\nGenerated by RentEase")
        }} catch (e: Exception) {}
    }

    // ── Load real uploaded documents from Firebase ────────────────────────────

    private fun loadMyDocuments() {
        val uid = SessionManager.getUid(this)
        if (uid.isEmpty()) return

        FirebaseHelper.getUserDocuments(uid,
            onSuccess = { docs ->
                if (docs.isEmpty()) return@getUserDocuments
                val container = try { findViewById<LinearLayout>(R.id.uploadedDocsContainer) } catch (e: Exception) { return@getUserDocuments }
                container.visibility = View.VISIBLE
                container.removeAllViews()

                docs.forEach { doc ->
                    val fileName = doc["fileName"] as? String ?: "Document"
                    val docType  = doc["docType"]  as? String ?: "General"
                    val url      = doc["downloadUrl"] as? String ?: ""

                    // Add a row for each uploaded doc
                    val row = layoutInflater.inflate(R.layout.item_document_row, container, false)
                    row.findViewById<TextView>(R.id.tvDocFileName)?.text = fileName
                    row.findViewById<TextView>(R.id.tvDocType)?.text     = docType
                    row.setOnClickListener { openDocumentUrl(url) }
                    container.addView(row)
                }
            },
            onError = { /* silently fail */ }
        )
    }

    // ── Show type picker before uploading ─────────────────────────────────────

    private fun showUploadTypeDialog() {
        val types = arrayOf("Lease agreement", "Payment receipt", "ID document", "Other")
        AlertDialog.Builder(this)
            .setTitle("What type of document?")
            .setItems(types) { _, which ->
                selectedDocType = types[which]
                pickFile()
            }
            .show()
    }

    // ── Open system file picker ───────────────────────────────────────────────

    private fun pickFile() {
        val intent = Intent(Intent.ACTION_GET_CONTENT).apply {
            type = "*/*"
            putExtra(Intent.EXTRA_MIME_TYPES, arrayOf(
                "application/pdf",
                "image/jpeg",
                "image/png",
                "image/jpg"
            ))
        }
        startActivityForResult(Intent.createChooser(intent, "Select document"), PICK_FILE_REQUEST)
    }

    override fun onActivityResult(requestCode: Int, resultCode: Int, data: Intent?) {
        super.onActivityResult(requestCode, resultCode, data)
        if (requestCode == PICK_FILE_REQUEST && resultCode == Activity.RESULT_OK) {
            val uri = data?.data ?: return
            val fileName = getFileName(uri) ?: "document_${System.currentTimeMillis()}"
            uploadFile(uri, fileName)
        }
    }

    // ── Upload the file to Firebase Storage ───────────────────────────────────

    private fun uploadFile(uri: Uri, fileName: String) {
        val uid = SessionManager.getUid(this)
        if (uid.isEmpty()) {
            toast("Please log in first")
            return
        }

        val progressBar = try { findViewById<ProgressBar>(R.id.pbUpload) } catch (e: Exception) { null }
        val tvProgress  = try { findViewById<TextView>(R.id.tvUploadProgress) } catch (e: Exception) { null }

        progressBar?.visibility = View.VISIBLE
        tvProgress?.visibility  = View.VISIBLE
        tvProgress?.text        = "Uploading... 0%"

        FirebaseHelper.uploadDocument(
            userId   = uid,
            fileUri  = uri,
            fileName = fileName,
            docType  = selectedDocType,
            onProgress = { percent ->
                runOnUiThread {
                    progressBar?.progress = percent
                    tvProgress?.text      = "Uploading... $percent%"
                }
            },
            onSuccess = { downloadUrl ->
                runOnUiThread {
                    progressBar?.visibility = View.GONE
                    tvProgress?.visibility  = View.GONE
                    toast("$fileName uploaded successfully!")
                    loadMyDocuments() // Refresh the list
                }
            },
            onError = { error ->
                runOnUiThread {
                    progressBar?.visibility = View.GONE
                    tvProgress?.visibility  = View.GONE
                    toast("Upload failed: $error")
                }
            }
        )
    }

    private fun getFileName(uri: Uri): String? {
        var result: String? = null
        if (uri.scheme == "content") {
            val cursor = contentResolver.query(uri, null, null, null, null)
            cursor?.use {
                if (it.moveToFirst()) {
                    val idx = it.getColumnIndex(OpenableColumns.DISPLAY_NAME)
                    if (idx >= 0) result = it.getString(idx)
                }
            }
        }
        if (result == null) {
            result = uri.path
            val cut = result?.lastIndexOf('/') ?: -1
            if (cut != -1) result = result?.substring(cut + 1)
        }
        return result
    }

    private fun showDocumentContent(title: String, content: String) {
        AlertDialog.Builder(this)
            .setTitle(title)
            .setMessage(content)
            .setPositiveButton("Close", null)
            .setNeutralButton("Share") { _, _ ->
                val shareIntent = Intent(Intent.ACTION_SEND).apply {
                    type = "text/plain"
                    putExtra(Intent.EXTRA_SUBJECT, title)
                    putExtra(Intent.EXTRA_TEXT, "$title\n\n$content")
                }
                startActivity(Intent.createChooser(shareIntent, "Share"))
            }
            .show()
    }

    private fun openDocumentUrl(url: String) {
        if (url.isEmpty()) return
        try {
            val intent = Intent(Intent.ACTION_VIEW, Uri.parse(url))
            startActivity(intent)
        } catch (e: Exception) {
            toast("Cannot open document")
        }
    }

    private fun toast(msg: String) =
        Toast.makeText(this, msg, Toast.LENGTH_SHORT).show()
}
